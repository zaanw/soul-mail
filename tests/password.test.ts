import { it, expect } from "vitest";
import { hashPassword, verifyPassword } from "../src/lib/password";
const legacy =
  "$argon2id$v=19$m=65536,t=3,p=1$c291bC10ZXN0LXNhbHQxNiE$B1nA5DU+QbQu0kjczvC/VY3JsfmlgOMUoP9ouFyiARw";
it("verifies an unchanged PHC hash generated by the previous native Argon2 module", async () => {
  expect(await verifyPassword(legacy, "legacy-compatibility-vector-only")).toBe(
    true,
  );
  expect(await verifyPassword(legacy, "incorrect")).toBe(false);
}, 20000);
it("uses independent salts and verifies UTF-8 passwords", async () => {
  const a = await hashPassword("пароль для проверки 123");
  const b = await hashPassword("пароль для проверки 123");
  expect(a).not.toBe(b);
  expect(await verifyPassword(a, "пароль для проверки 123")).toBe(true);
}, 20000);
it("rejects corrupt hashes and unbounded cost parameters before allocation", async () => {
  expect(await verifyPassword(legacy.replace("65536", "999999999"), "x")).toBe(
    false,
  );
  expect(await verifyPassword("corrupt", "x")).toBe(false);
});
